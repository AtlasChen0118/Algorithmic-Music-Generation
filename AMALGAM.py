def smooth_voicing(tones, prev_voicing=None, desired_size=4):
    tones = sorted(tones)
    if len(tones) >= desired_size:
        base = tones[:desired_size]
    else:
        base = tones[:]
        while len(base) < desired_size:
            base.append(base[-1] + 12)

    if prev_voicing is None:
        return base

    voiced = []
    for i, p in enumerate(base):
        target = prev_voicing[min(i, len(prev_voicing) - 1)]
        cands = [p - 12, p, p + 12, p + 24]
        best = min(cands, key=lambda x: abs(x - target))
        voiced.append(best)

    # Sorting prevents crossing, but does not currently prevents overlapping voices.
    voiced = sorted(voiced)
    return voiced

