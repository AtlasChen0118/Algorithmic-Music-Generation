def melodic_minor_adjust(pool, key="C", prev_pitch=None, max_leap=7):
    tonic_pc = NOTE_TO_PC[key]
    nat6_pc = (tonic_pc + 8) % 12
    nat7_pc = (tonic_pc + 10) % 12

    adjusted = []
    for p in pool:
        if (p % 12) == nat6_pc and prev_pitch is not None and p > prev_pitch and abs((p + 1) - prev_pitch) <= max_leap:
            adjusted.append(p + 1)
        elif (p % 12) == nat7_pc and prev_pitch is not None and p > prev_pitch and abs((p + 1) - prev_pitch) <= max_leap:
            adjusted.append(p + 1)
        else:
            adjusted.append(p)
    return sorted(set(adjusted))

# Define a dynamic pool of usable beats according to the roles for each note
def choose_pool_by_metric(role, chord_tones, scale_tones, next_chord_tones=None):
    chord_pcs = {p % 12 for p in chord_tones}
    nonchord = [p for p in scale_tones if (p % 12) not in chord_pcs]

    if next_chord_tones is None:
        next_chord_tones = []

    # Define an anticipation zone that allows the melody to be generated based on the NEXT chord progression
    next_chord_pcs = {n % 12 for n in next_chord_tones}
    anticipation = [
        p for p in scale_tones
        if (p % 12) in next_chord_pcs
        and (p % 12) not in chord_pcs
    ]

    # Probability patterns, self explanatory
    if role == "bar_downbeat":
        pool = chord_tones * 10 + nonchord * 1
    elif role == "midbar_strong":
        pool = chord_tones * 7 + nonchord * 2
    elif role == "beat":
        pool = chord_tones * 4 + nonchord * 3
    else:
        pool = chord_tones * 2 + nonchord * 5 + anticipation * 2

    return pool

# The Contour Filter endows a Multiplication process to all notes that fit the desired contour.
# e.g. if you are on 67 and have [64, 65, 68] in the pool with an "UP" contour,
# The code multiplies the 68 by 3 and output [64, 65, 68, 68, 68].
# Similarly, a "DOWN" contour would give [64, 64, 64, 65, 65, 65, 68]
def contour_filter(candidates, prev_pitch, contour, bar_progress):
    if prev_pitch is None:
        return candidates

    if contour == "up":
        weighted = candidates + [p for p in candidates if p >= prev_pitch] * 3

    elif contour == "down":
        weighted = candidates + [p for p in candidates if p <= prev_pitch] * 3

    # TODO: Do a smart filter on convex and concave arch - previously tried, unsuccessful so cut out of the code >>>>>>>>>>>>>>>>>>>>>>>>>>
    elif contour == "arch":
        if bar_progress < 0.5:
            weighted = candidates + [p for p in candidates if p >= prev_pitch] * 2
        else:
            weighted = candidates + [p for p in candidates if p <= prev_pitch] * 2

    elif contour == "wave":
        if int(bar_progress * 4) % 2 == 0:
            weighted = candidates + [p for p in candidates if p >= prev_pitch] * 2
        else:
            weighted = candidates + [p for p in candidates if p <= prev_pitch] * 2

    else:
        weighted = candidates

    return weighted if weighted else candidates


# If an interval of 3rd, 4th or 5th would be produced, consider invoking the function and smoothen it out by inserting an arith avg note in between
def choose_stepwise_nonchord(prev_pitch, target_pitch, scale_pool):

    low = min(prev_pitch, target_pitch)
    high = max(prev_pitch, target_pitch)

    between = [p for p in scale_pool if low < p < high]

    if abs(target_pitch - prev_pitch) in (3, 4, 5) and between:
        return weighted_choice(between, center=(prev_pitch + target_pitch) / 2)

    neighbors = [p for p in scale_pool if abs(p - prev_pitch) in (1, 2)]
    if neighbors:
        return random.choice(neighbors)

    return target_pitch

