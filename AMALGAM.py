def generate_melody(progression, bpm=200, ticks_per_beat=4, beats_per_bar=4,
                    key="C", scale_type="major",
                    rest_prob=0.08, max_leap=7, center_pitch=72,
                    activity=0.60, ending_bars=1):
    global notes_track
    notes_track = np.zeros(0)

    beat_sec = 60.0 / bpm
    tick_sec = beat_sec / ticks_per_beat

    total_ticks = sum(L for _, L in progression)
    total_time = total_ticks * tick_sec
    blocks = _build_progression_blocks(progression)

    scale_main = build_scale(key=key, scale_type=scale_type, octaves=(4, 5))
    scale_nat  = build_scale(key=key, scale_type="nat_minor", octaves=(4, 5))

    tick = 0
    now = 0.0
    prev_pitch = None
    ending_ticks = ticks_per_beat * beats_per_bar * ending_bars

    while tick < total_ticks:
        remaining_ticks = total_ticks - tick

        # End phase logistics
        if remaining_ticks <= ending_ticks:
            prev_pitch = add_ending_sentence(
                start_time=now,
                remaining_ticks=remaining_ticks,
                tick_sec=tick_sec,
                key=key,
                scale_type=scale_type,
                prev_pitch=prev_pitch,
                center_pitch=center_pitch
            )
            break
        bar_ticks = min(ticks_per_beat * beats_per_bar, total_ticks - tick)
        contour = choose_phrase_contour()
        rhythm = fill_bar_with_cells(bar_ticks, activity=activity)

        local_tick = 0

        # Run the CT/NCT filter for each "bar" predefined in the rhythm pattern
        for dur in rhythm:
            if tick >= total_ticks:
                break

            curr_sym, _, chord_start, next_sym = chord_at_tick(blocks, tick)
            role = metric_role(tick, ticks_per_beat=ticks_per_beat, beats_per_bar=beats_per_bar)


            # We now generate every CT along with the NEXT CT before filling in the NCT in between for better phrase accomodation
            chord_tones_strong = chord_midi_tones(curr_sym, octaves=(4, 5), include_upper_color=False)
            chord_tones_weak   = chord_midi_tones(curr_sym, octaves=(4, 5), include_upper_color=True)
            next_chord_tones   = chord_midi_tones(next_sym, octaves=(4, 5), include_upper_color=False)

            # Better 6th and 7th raise checks for Melodic Minor now based on the movements
            if scale_type.lower() in ("melo_minor", "melodic_minor", "melodic"):
                scale_pool = melodic_minor_adjust(scale_nat + chord_tones_weak, key=key, prev_pitch=prev_pitch, max_leap=max_leap)
            else:
                scale_pool = sorted(set(scale_main + chord_tones_weak))

            cycle_pos = tick
            boundary_cut = None
            for sym2, L2, start2 in blocks:
                db = start2
                if tick < db < tick + dur: # We preserve the logic that avoids generation from passing through a strong beat
                    boundary_cut = db - tick
                    break
            if boundary_cut is not None and boundary_cut > 0:
                dur = boundary_cut

            bar_progress = local_tick / max(1, bar_ticks)

            # Optional rest can now occur on weaker positions only
            if role in ("beat", "offbeat") and random.random() < rest_prob: # The default is now 8%
                tick += dur
                now += dur * tick_sec
                local_tick += dur
                continue

            pool = choose_pool_by_metric(role, chord_tones_strong, scale_pool, next_chord_tones=next_chord_tones)
            pool = in_range(pool, 60, 84) # 72 +- 12

            if not pool:
                pool = chord_tones_strong[:]

            pool = contour_filter(pool, prev_pitch, contour, bar_progress)

            if role in ("bar_downbeat", "midbar_strong"): # Strong position
                cand = weighted_choice(pool, center=center_pitch)
                cand = no_big_leap(prev_pitch, cand, pool, max_leap=max_leap)

            elif role == "beat":
                base = weighted_choice(pool, center=center_pitch)
                base = no_big_leap(prev_pitch, base, pool, max_leap=max_leap)
                cand = base

            else:  # offbeat
                target_pool = in_range(next_chord_tones + chord_tones_strong, 60, 84) # Offbeat - Onbeat should bias toward smooth motion
                if target_pool:
                    target = weighted_choice(target_pool, center=center_pitch)
                else:
                    target = weighted_choice(chord_tones_strong, center=center_pitch)

                if prev_pitch is not None and random.random() < 0.65: # Alterable - Feel free to change. Currently 65% of the time the algorithm favors smooth steps
                    cand = choose_stepwise_nonchord(prev_pitch, target, scale_pool) # Focus on smooth motion
                else:
                    cand = weighted_choice(pool, center=center_pitch)

                cand = no_big_leap(prev_pitch, cand, pool, max_leap=max_leap)

            add_note_to("melody", cand, now, dur * tick_sec, amp=1.0, timbre="melody")
            prev_pitch = cand
            tick += dur
            now += dur * tick_sec
            local_tick += dur

    return total_time


