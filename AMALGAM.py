def _build_progression_blocks(progression):
    blocks = []
    s = 0
    for sym, L in progression:
        blocks.append((sym, L, s))
        s += L
    return blocks

def chord_at_tick(blocks, tick):
    for i, (sym, L, start) in enumerate(blocks):
        if start <= tick < start + L:
            next_sym = blocks[(i + 1) % len(blocks)][0]
            return sym, L, start, next_sym
    sym, L, start = blocks[-1]
    return sym, L, start, blocks[0][0]

# This improved entire chunk is responsible for generating the underlying chords.
# There are currently Blocks, Bass Chords, Arpeggio and Waltz available.
def generate_chord_background(progression, bpm=200, ticks_per_beat=4,
                              chord_octaves=(3, 4), chord_amp=0.18,
                              style="arpeggio"):
    global chord_track
    chord_track = np.zeros(0)

    beat_sec = 60.0 / bpm
    tick_sec = beat_sec / ticks_per_beat

    now = 0.0
    prev_voicing = None

    # Process chords
    for sym, L in progression:
        tones = chord_midi_tones(sym, octaves=chord_octaves, include_upper_color=False)
        tones = sorted(tones)
        dur_sec = L * tick_sec

        if style == "block": # Block chords
            voicing = smooth_voicing(tones, prev_voicing=prev_voicing, desired_size=4)
            for p in voicing:
                add_note_to("chords", p, now, dur_sec, amp=chord_amp, timbre="chord")
            prev_voicing = voicing

        elif style == "bass_chord": # Bass chords
            ticks_left = L
            t = 0
            voicing = smooth_voicing(tones, prev_voicing=prev_voicing, desired_size=4)
            bass = min(voicing)
            upper = voicing[1:]

            while ticks_left > 0:
                step = min(ticks_per_beat, ticks_left)
                # Have the bass ends before the next one begins for better effect
                add_note_to("chords", bass, now + t * tick_sec, step * tick_sec * 0.95, amp=chord_amp * 1.15, timbre="bass")

                # Have a stab kick in at 0.48 interval (which sounds better than 0.5)
                stab_start = now + t * tick_sec + (step * tick_sec) * 0.48
                stab_dur   = max(0.04, step * tick_sec * 0.35)
                for p in upper:
                    add_note_to("chords", p, stab_start, stab_dur, amp=chord_amp * 0.75, timbre="chord")

                t += step
                ticks_left -= step

            prev_voicing = voicing

        elif style == "arpeggio": # Arpeggios
            voicing = smooth_voicing(tones, prev_voicing=prev_voicing, desired_size=4)
            pattern_idx = [0, 1, 2, 1, 3, 2, 1, 2] # Alterable! Currently something like C1 - E - G - E - C2 - E - G - E
            for i in range(L):
                p = voicing[pattern_idx[i % len(pattern_idx)]]
                # Again, have the note end a little bit earlier for better effect
                add_note_to("chords", p, now + i * tick_sec, tick_sec * 0.95, amp=chord_amp, timbre="chord")
            prev_voicing = voicing

        elif style == "waltz": # DUM - ba - ba - DUM - ba - ba
            voicing = smooth_voicing(tones, prev_voicing=prev_voicing, desired_size=4)
            bass = min(voicing)
            upper = voicing[1:]
            for i in range(L):
                if i % ticks_per_beat == 0:
                    add_note_to("chords", bass, now + i * tick_sec, tick_sec * 0.95, amp=chord_amp * 1.2, timbre="bass")
                else:
                    for p in upper:
                        add_note_to("chords", p, now + i * tick_sec, tick_sec * 0.8, amp=chord_amp * 0.7, timbre="chord")
            prev_voicing = voicing

        else:
            raise ValueError("Bruh") # Bruh

        now += dur_sec

    return now

