def mix_tracks(melody_gain=0.85, counter_gain=0.55, chord_gain=0.60):
    max_len = max(len(notes_track), len(counter_track), len(chord_track), 1)

    mel = _ensure_len(notes_track.copy(), max_len) if len(notes_track) else np.zeros(max_len)
    ctr = _ensure_len(counter_track.copy(), max_len) if len(counter_track) else np.zeros(max_len)
    chd = _ensure_len(chord_track.copy(), max_len) if len(chord_track) else np.zeros(max_len)

    mix = melody_gain * mel + counter_gain * ctr + chord_gain * chd

    peak = np.max(np.abs(mix))
    if peak > 0.98:
        mix = 0.98 * mix / peak

    return mix

