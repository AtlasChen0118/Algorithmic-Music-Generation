# Revised Weighted Selection
# The weight of selecting each note is now 1/(1 + Distance) for each note based on its distance away from the center (default C5)
def weighted_choice(pitches, center=72):
    if not pitches:
        raise ValueError("weighted_choice called with empty pitches")

    weights = [1.0 / (1.0 + abs(p - center)) for p in pitches]
    total = sum(weights)
    r = random.random() * total
    acc = 0.0

    for p, w in zip(pitches, weights):
        acc += w
        if acc >= r:
            return p
    return random.choice(pitches)

