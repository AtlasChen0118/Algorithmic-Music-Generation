def pc_to_midi(pc, octave=4):
    return 12 * (octave + 1) + pc

def build_scale(key="C", scale_type="major", octaves=(4, 5)):
    major      = [0, 2, 4, 5, 7, 9, 11]
    nat_minor  = [0, 2, 3, 5, 7, 8, 10]
    harm_minor = [0, 2, 3, 5, 7, 8, 11]
    melo_minor = [0, 2, 3, 5, 7, 9, 11]

    st = scale_type.lower()
    if st == "major":
        base = major
    elif st in ("nat_minor", "natural_minor", "natural"):
        base = nat_minor
    elif st in ("harm_minor", "harmonic_minor", "harmonic"):
        base = harm_minor
    elif st in ("melo_minor", "melodic_minor", "melodic"):
        base = melo_minor
    else:
        raise ValueError("scale_type must be one of: major, nat_minor, harm_minor, melo_minor")

    tonic_pc = NOTE_TO_PC[key]
    out = []
    for octv in octaves:
        for i in base:
            out.append(pc_to_midi((tonic_pc + i) % 12, octv))
    return sorted(out)

def parse_chord_symbol(sym):
    s = sym.strip()
    m = re.match(r"^([A-G])([#b]?)(.*)$", s)

    if not m:
        raise ValueError(f"Bad chord symbol: {sym}")

    root = m.group(1) + m.group(2)
    rest = (m.group(3) or "").strip()

    root_pc = NOTE_TO_PC[root]
    rlow = rest.lower()

    is_maj = False
    is_min = False
    is_dim = False
    is_aug = False
    has_7  = False
    maj7   = False

    if "maj7" in rlow or "ma7" in rlow or "m7+" in rlow or "Δ" in rest or ("m7" in rest and "maj" in rlow):
        is_maj = True
        has_7 = True
        maj7 = True
    elif "maj" in rlow or ("m7" in rest and "Δ" in rest):
        is_maj = True

    if ("min" in rlow) or (rlow.startswith("m") and not rlow.startswith("maj")) or ("-" in rest):
        is_min = True

    if "dim" in rlow or "o" in rest:
        is_dim = True
    if "aug" in rlow or "+" in rest:
        is_aug = True

    if ("7" in rlow) and not maj7:
        has_7 = True

    if is_dim:
        is_maj = is_min = is_aug = False
    if is_aug:
        is_maj = True
        is_min = False

    if not (is_maj or is_min or is_dim or is_aug):
        is_maj = True

    if is_dim:
        triad = [0, 3, 6]
        seventh = 9
    elif is_min:
        triad = [0, 3, 7]
        seventh = 10
    elif is_aug:
        triad = [0, 4, 8]
        seventh = 10
    else:
        triad = [0, 4, 7]
        seventh = 11 if maj7 else 10

    tones = triad[:]
    if has_7 or maj7:
        tones.append(seventh)

    pcs = [(root_pc + i) % 12 for i in tones]
    return root_pc, pcs

def chord_midi_tones(sym, octaves=(4, 5), include_upper_color=True):
    root_pc, pcs = parse_chord_symbol(sym)

    out = []
    for octv in octaves:
        for pc in pcs:
            out.append(pc_to_midi(pc, octv))

    if include_upper_color:
        for add_int in [2, 5, 9]:
            pc = (root_pc + add_int) % 12
            out.append(pc_to_midi(pc, octaves[-1]))

    return sorted(set(out))

def chord_pitch_classes(sym, include_upper_color=False):
    _, pcs = parse_chord_symbol(sym)
    out = set(pcs)
    if include_upper_color:
        root_pc, _ = parse_chord_symbol(sym)
        for add_int in [2, 5, 9]:
            out.add((root_pc + add_int) % 12)
    return out

