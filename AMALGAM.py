def metric_role(tick, ticks_per_beat=4, beats_per_bar=4):
    ticks_per_bar = ticks_per_beat * beats_per_bar
    pos = tick % ticks_per_bar

    if pos == 0:
        return "bar_downbeat"      # beat 1
    elif pos == 2 * ticks_per_beat:
        return "midbar_strong"     # beat 3
    elif pos % ticks_per_beat == 0:
        return "beat"              # beats 2 and 4
    else:
        return "offbeat"

def choose_phrase_contour(): # Phrase contours for random choice
    return random.choice(["up", "down", "arch", "wave"])

# Predefine some rhythm cells in order for the melody to sound more rooted
RHYTHM_CELLS = [
    [4, 4, 4, 4],
    [8, 4, 4],
    [4, 2, 2, 4, 4],
    [2, 2, 4, 2, 2, 4],
    [6, 2, 4, 4],
    [4, 4, 2, 2, 4],
    [2, 2, 2, 2, 4, 4],
    [4, 2, 2, 2, 2, 4],
]

# In melodic expression density with less than 0.7 we only apply the calm ones
def choose_rhythm_cell(activity=0.5):
    if activity < 0.3:
        choices = RHYTHM_CELLS[:3]
    elif activity < 0.7:
        choices = RHYTHM_CELLS[:8]
    else:
        choices = RHYTHM_CELLS
    return random.choice(choices)

# Do a redivision of bars based on the rhythm cells we had
def fill_bar_with_cells(bar_ticks, activity=0.5):
    out = []
    remaining = bar_ticks

    while remaining > 0:
        cell = choose_rhythm_cell(activity=activity)
        total = sum(cell)

        if total <= remaining:
            out.extend(cell)
            remaining -= total
        else:
            # fallback: fill remaining more conservatively
            if remaining in (1, 2, 3, 4, 6, 8):
                out.append(remaining)
            else:
                out.append(4)
                remaining -= 4
                continue
            remaining = 0

    return out

