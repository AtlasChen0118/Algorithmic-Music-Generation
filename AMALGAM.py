def no_big_leap(prev_pitch, candidate_pitch, allowed_pool, max_leap=7):
    if prev_pitch is None:
        return candidate_pitch
    if abs(candidate_pitch - prev_pitch) <= max_leap:
        return candidate_pitch
    close = [p for p in allowed_pool if abs(p - prev_pitch) <= max_leap]
    return random.choice(close) if close else candidate_pitch

# Searching helpers
def nearest_pitch_with_pc(pc, register_center=72, search_low=48, search_high=96):
    candidates = [p for p in range(search_low, search_high + 1) if (p % 12) == pc]
    return min(candidates, key=lambda p: abs(p - register_center))

def nearest_from_pool(pool, target):
    return min(pool, key=lambda p: abs(p - target))

def in_range(pool, low, high):
    return [p for p in pool if low <= p <= high]

# Instead of doing a fixed chord for each chord progression input,
# we now try to find the smoothest voice leading possible by having each note moves to the nearest chord independently.
