def _ending_durations(remaining_ticks):
    if remaining_ticks <= 1:
        return [remaining_ticks]

    if remaining_ticks == 2:
        return [1, 1]

    if remaining_ticks == 3:
        return [1, 1, 1]

    # Rough shape: 1/4, 1/8, 1/8, 1/2
    d1 = max(1, remaining_ticks // 4)
    d2 = max(1, remaining_ticks // 8)
    d3 = max(1, remaining_ticks // 8)
    d4 = remaining_ticks - d1 - d2 - d3

    # Make sure the final duration is at least 1
    while d4 < 1:
        if d3 > 1:
            d3 -= 1
        elif d2 > 1:
            d2 -= 1
        elif d1 > 1:
            d1 -= 1
        d4 = remaining_ticks - d1 - d2 - d3

    return [d1, d2, d3, d4]


def _ending_sentence_pitches(key="C", scale_type="major", prev_pitch=None, center_pitch=72):
    tonic_pc = NOTE_TO_PC[key]
    dominant_pc = (tonic_pc + 7) % 12
    supertonic_pc = (tonic_pc + 2) % 12

    st = scale_type.lower()
    if st in ("nat_minor", "natural_minor", "natural"):
        lead_pc = (tonic_pc + 10) % 12   # b7
    else:
        lead_pc = (tonic_pc + 11) % 12   # leading tone

    # Pick a simple cadential pattern
    if st in ("nat_minor", "natural_minor", "natural"):
        pcs = [dominant_pc, lead_pc, supertonic_pc, tonic_pc]
    else:
        pcs = [dominant_pc, supertonic_pc, lead_pc, tonic_pc]

    pitches = []
    target = prev_pitch if prev_pitch is not None else center_pitch

    for i, pc in enumerate(pcs):
        p = nearest_pitch_with_pc(pc, register_center=target, search_low=60, search_high=84)

        # Try to keep it reasonably singable / connected
        if pitches:
            while p - pitches[-1] > 7 and p - 12 >= 60:
                p -= 12
            while pitches[-1] - p > 7 and p + 12 <= 84:
                p += 12

        pitches.append(p)
        target = p

    # Force the very last note to be a tonic near the center,
    # so it feels final and stable
    pitches[-1] = nearest_pitch_with_pc(tonic_pc, register_center=center_pitch, search_low=60, search_high=84)

    return pitches


def add_ending_sentence(start_time, remaining_ticks, tick_sec,
                        key="C", scale_type="major",
                        prev_pitch=None, center_pitch=72):
    """
    Writes a fixed cadential ending into the melody track.
    """
    durs = _ending_durations(remaining_ticks)
    pitches = _ending_sentence_pitches(
        key=key,
        scale_type=scale_type,
        prev_pitch=prev_pitch,
        center_pitch=center_pitch
    )

    t = start_time
    last_pitch = prev_pitch

    # If we have fewer durations than 4 because remaining_ticks is tiny,
    # just use the tail of the cadence.
    pitches = pitches[-len(durs):]

    for i, (p, dur) in enumerate(zip(pitches, durs)):
        # Slight emphasis on the final note
        amp = 1.15 if i == len(durs) - 1 else 1.0
        add_note_to("melody", p, t, dur * tick_sec, amp=amp, timbre="melody")
        t += dur * tick_sec
        last_pitch = p

    return last_pitch

