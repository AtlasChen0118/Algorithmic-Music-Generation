def _ensure_len(buf, end_n):
    if len(buf) < end_n:
        buf = np.append(buf, np.zeros(end_n - len(buf)))
    return buf

# We now generated different notes in different timbre according to its role.
def _synth_tone(pitch, dur_n, sr, timbre="melody"):
    f = 440 * 2 ** ((pitch - 69) / 12)
    theta = 2 * np.pi * f * np.arange(dur_n) / sr

    # For melody, we put its 2nd - 5th harmonics over it for a richer sense with nth harmonic at 1/n weight
    if timbre == "melody":
        note = np.sin(theta)
        for n in range(2, 6):
            note += (1 / n) * np.sin(n * theta)
        note *= np.logspace(0, -2, dur_n)

    # For the chord, we have 1f1 + 0.5f2 + 0.25f3
    elif timbre == "chord":
        note = np.sin(theta)
        note += 0.5 * np.sin(2 * theta)
        note += 0.25 * np.sin(3 * theta)
        note *= np.logspace(0, -1.7, dur_n)

    # For the bass, we have 1.2 Fundamental + 0.25f2
    elif timbre == "bass":
        note = 1.2 * np.sin(theta)
        note += 0.25 * np.sin(2 * theta)
        note *= np.logspace(0, -1.3, dur_n)

    else:
        note = np.sin(theta)
        note *= np.logspace(0, -2, dur_n)

    return note

# We now have to manage 2 different tracks so melodies and chords can be defaulted into their separated tracks.
# Bass notes goes into the Chords track in later implementations by default.
def add_note_to(buffer_name, pitch, start, duration, amp=1.0, timbre=None):
    global notes_track, chord_track

    start_n = int(start * sr)
    dur_n = max(1, int(duration * sr))
    end_n = start_n + dur_n

    if buffer_name == "melody":
        notes_track = _ensure_len(notes_track, end_n)
        buf = notes_track

        if timbre is None:
            timbre = "melody"

    elif buffer_name == "chords":
        chord_track = _ensure_len(chord_track, end_n)
        buf = chord_track

        if timbre is None:
            timbre = "chord"

    else:
        raise ValueError("Bruh in Add Note Function") # Bruh

    # Synthesize
    note = _synth_tone(pitch, dur_n, sr, timbre=timbre)
    note *= amp
    buf[start_n:end_n] += note

    if buffer_name == "melody":
        notes_track = buf
    else:
        chord_track = buf

